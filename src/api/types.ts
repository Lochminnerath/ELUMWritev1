/**
 * Shared data shapes for the ELUM API. The local API and the HTTP API both
 * speak these types, so the UI never knows which one is behind it.
 */

/** What someone can do with a document. Owner > editor > commenter > viewer. */
export type Role = 'owner' | 'editor' | 'commenter' | 'viewer';
export type ShareRole = Exclude<Role, 'owner'>;

/**
 * `type`: an ELUM Type inbox (coming later; those accounts sign in through the inbox).
 * `external`: the person's own email provider. Share emails go to that address.
 */
export type AccountType = 'type' | 'external';

export interface User {
  id: string;
  name: string;
  email: string;
  /** Avatar colour, one of the product colours. */
  color: string;
  accountType: AccountType;
  createdAt: string;
  /** Their profile picture (set in ELUM Account), as a link the browser can load. */
  pictureUrl?: string | null;
}

export type PublicUser = Pick<User, 'id' | 'name' | 'email' | 'color'>;

export interface Session {
  token: string;
  user: User;
  expiresAt: string;
}

export interface SignUpInput {
  name: string;
  /** Their own email, for `external` accounts. Unused for Type accounts. */
  email: string;
  password: string;
  /** Defaults to `external`. `type` creates an ELUM Type address (needs the ELUM platform). */
  accountType?: AccountType;
  /** Type accounts: the name before @<type domain>. */
  handle?: string;
  /** Type accounts: an outside address for getting back in after a forgotten password. */
  recoveryEmail?: string;
}

export interface SignInInput {
  /** An email, an ELUM Type address, or just the name before @<type domain>. */
  email: string;
  password: string;
}

/** ProseMirror/TipTap document JSON. Kept structural so the API layer has no editor dependency. */
export interface DocMark {
  type: string;
  attrs?: Record<string, unknown>;
}

export interface DocNode {
  type: string;
  attrs?: Record<string, unknown>;
  content?: DocNode[];
  marks?: DocMark[];
  text?: string;
}

/** A tiny outline of the first blocks of a document, used to draw thumbnails. */
export interface PreviewBlock {
  kind: 'heading' | 'text' | 'list' | 'image' | 'rule' | 'quote';
  text?: string;
  level?: number;
}

export interface DocumentSummary {
  id: string;
  title: string;
  owner: PublicUser;
  /** The signed-in person's role on this document. */
  role: Role;
  createdAt: string;
  updatedAt: string;
  updatedBy: PublicUser | null;
  lastOpenedAt: string | null;
  preview: PreviewBlock[];
  sharedWithCount: number;
}

export interface DocumentRecord extends DocumentSummary {
  content: DocNode;
  version: number;
}

export type DocumentFilter = 'all' | 'owned' | 'shared';

export interface SaveDocumentInput {
  content: DocNode;
  /** The version the client started from. A mismatch is a conflict unless `force` is set. */
  baseVersion: number;
  force?: boolean;
}

export interface SaveResult {
  version: number;
  updatedAt: string;
}

export interface Share {
  user: PublicUser;
  role: ShareRole;
  addedAt: string;
  addedBy: PublicUser | null;
}

/** Access waiting for someone who has no account yet. It applies once they verify this address. */
export interface Invite {
  email: string;
  role: ShareRole;
  invitedAt: string;
  invitedBy: PublicUser | null;
}

export type ShareByEmailResult = { kind: 'share'; share: Share } | { kind: 'invite'; invite: Invite };

export interface CommentReply {
  id: string;
  author: PublicUser;
  body: string;
  createdAt: string;
}

export interface CommentThread {
  /** Generated by the client so the anchor mark can be placed in the document. */
  id: string;
  docId: string;
  author: PublicUser;
  body: string;
  /** The text the comment was anchored to when it was made. */
  quote: string;
  createdAt: string;
  resolved: boolean;
  resolvedAt: string | null;
  resolvedBy: PublicUser | null;
  replies: CommentReply[];
}

export interface NewComment {
  id: string;
  body: string;
  quote: string;
}

export interface Asset {
  id: string;
  /** Value to store in the document. Pass it to `resolveAssetUrl` to display it. */
  url: string;
  mimeType: string;
  size: number;
}

/** One of the ELUM products, as the platform lists them. */
export type ServiceId = 'write' | 'type' | 'browse' | 'make' | 'store';

/** Something that happened in any ELUM service, for the person's bell. */
export interface AppNotification {
  id: string;
  service: ServiceId | 'elum';
  type: string;
  title: string;
  body: string | null;
  /** A path inside the service, or a full URL. */
  link: string | null;
  createdAt: string;
  readAt: string | null;
  actor: Pick<PublicUser, 'id' | 'name' | 'color'> | null;
}
